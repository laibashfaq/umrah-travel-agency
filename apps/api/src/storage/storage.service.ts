import { randomUUID } from 'node:crypto';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { DeleteObjectCommand, GetObjectCommand, PutObjectCommand, S3Client } from '@aws-sdk/client-s3';
import { Global, Inject, Injectable, Module } from '@nestjs/common';
import { ENV } from '../config/config.module';
import type { Env } from '../config/env';

/** Where private files live. Callers only ever see opaque keys, never paths or URLs. */
export interface ObjectStore {
  put(key: string, body: Buffer, contentType: string): Promise<void>;
  get(key: string): Promise<Buffer>;
  remove(key: string): Promise<void>;
}

/** Development driver: files under a folder that is not served by anything. */
export class LocalObjectStore implements ObjectStore {
  constructor(private readonly root: string) {}

  private resolve(key: string): string {
    const file = path.resolve(this.root, key);
    // Keys are generated by us, but never let one climb out of the folder.
    if (!file.startsWith(path.resolve(this.root) + path.sep)) throw new Error('Invalid storage key');
    return file;
  }

  async put(key: string, body: Buffer): Promise<void> {
    const file = this.resolve(key);
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, body, { mode: 0o600 });
  }

  get(key: string): Promise<Buffer> {
    return readFile(this.resolve(key));
  }

  async remove(key: string): Promise<void> {
    await rm(this.resolve(key), { force: true });
  }
}

/** Production driver: the private bucket, encrypted at rest. Access is only ever through this API after authorization. */
export class S3ObjectStore implements ObjectStore {
  constructor(
    private readonly client: S3Client,
    private readonly bucket: string,
  ) {}

  async put(key: string, body: Buffer, contentType: string): Promise<void> {
    await this.client.send(new PutObjectCommand({ Bucket: this.bucket, Key: key, Body: body, ContentType: contentType, ServerSideEncryption: 'AES256' }));
  }

  async get(key: string): Promise<Buffer> {
    const res = await this.client.send(new GetObjectCommand({ Bucket: this.bucket, Key: key }));
    if (!res.Body) throw new Error('Empty object');
    return Buffer.from(await res.Body.transformToByteArray());
  }

  async remove(key: string): Promise<void> {
    await this.client.send(new DeleteObjectCommand({ Bucket: this.bucket, Key: key }));
  }
}

@Injectable()
export class StorageService {
  private readonly store: ObjectStore;

  constructor(@Inject(ENV) env: Env) {
    if (env.STORAGE_DRIVER === 's3') {
      this.store = new S3ObjectStore(new S3Client({ region: env.AWS_REGION }), env.S3_PRIVATE_BUCKET);
    } else {
      const root = path.isAbsolute(env.STORAGE_LOCAL_DIR) ? env.STORAGE_LOCAL_DIR : path.resolve(process.cwd(), '../..', env.STORAGE_LOCAL_DIR);
      this.store = new LocalObjectStore(root);
    }
  }

  /** A fresh, unguessable key; the original file name is never part of it. */
  newKey(): string {
    const d = new Date();
    return `documents/${d.getUTCFullYear()}/${String(d.getUTCMonth() + 1).padStart(2, '0')}/${randomUUID()}`;
  }

  put(key: string, body: Buffer, contentType: string) {
    return this.store.put(key, body, contentType);
  }
  get(key: string) {
    return this.store.get(key);
  }
  remove(key: string) {
    return this.store.remove(key);
  }
}

@Global()
@Module({ providers: [StorageService], exports: [StorageService] })
export class StorageModule {}
